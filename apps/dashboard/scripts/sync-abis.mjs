// Regenerates src/abi/*.ts from the compiled contracts, so the dashboard never
// carries hand-written ABIs that can drift from what is deployed.
//
//   (cd ../../contracts && npx hardhat compile) && node scripts/sync-abis.mjs
//
// ChainPe contracts come from contracts/artifacts; the ERC-8004 registries
// (Arc's canonical deployments) from the vendored contracts/abis/erc8004.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const contracts = join(here, '../../../contracts')
const out = join(here, '../src/abi')

const SOURCES = {
  chainPeRegistry: 'artifacts/contracts/ChainPeRegistryUpgradeable.sol/ChainPeRegistryUpgradeable.json',
  policyVault: 'artifacts/contracts/PolicyVaultUpgradeable.sol/PolicyVaultUpgradeable.json',
  chainPeTimelock: 'artifacts/contracts/governance/ChainPeTimelock.sol/ChainPeTimelock.json',
  identityRegistry: 'abis/erc8004/IdentityRegistry.json',
  reputationRegistry: 'abis/erc8004/ReputationRegistry.json',
  validationRegistry: 'abis/erc8004/ValidationRegistry.json',
}

mkdirSync(out, { recursive: true })
const index = []
for (const [name, rel] of Object.entries(SOURCES)) {
  const json = JSON.parse(readFileSync(join(contracts, rel), 'utf8'))
  const abi = Array.isArray(json) ? json : json.abi
  const constName = `${name}Abi`
  writeFileSync(
    join(out, `${name}.ts`),
    `// GENERATED by scripts/sync-abis.mjs from contracts/${rel}. Do not edit.\n` +
      `export const ${constName} = ${JSON.stringify(abi, null, 2)} as const\n`,
  )
  index.push(`export { ${constName} } from './${name}'`)
  console.log(`wrote src/abi/${name}.ts (${abi.length} entries)`)
}
writeFileSync(join(out, 'index.ts'), `// GENERATED by scripts/sync-abis.mjs. Do not edit.\n${index.join('\n')}\n`)
